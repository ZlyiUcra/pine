// Classifying one simulateLadder() result for the combination-survival
// sweep - the single definition of "survived" shared by the CLI and the
// GUI, so the two surfaces cannot silently disagree about what the word
// means (consilium 2026-08-09).
//
// Three outcomes, mutually exclusive and exhaustive over every result:
//
//   'blew_up'       result.blowups.length > 0. Once a sequence has emptied
//                   the ladder once, nothing else about the run matters -
//                   this always wins regardless of what happened before or
//                   after.
//   'open_at_end'   never blew up, but result.openAtEnd is non-null: a
//                   sequence was still mid-ladder when the log ran out.
//                   Its stakes so far are real, but whether it would have
//                   won or blown up next is unknown - counting it as either
//                   "survived" or "blew up" would be a claim the data does
//                   not support (user decision, 2026-08-09, after
//                   measuring that 76% of naively-"survived" candidates on
//                   a real log were actually this).
//   'survived'      resolved cleanly (no blowup, nothing left open) AND
//                   ended the period in profit - the same rule
//                   isAcceptable() in the GUI already applies to its own
//                   suggestion tables (user request, 2026-08-08). A
//                   resolved run that never blew up but still lost money on
//                   net is deliberately NOT called "survived": it is
//                   reported separately by the caller as a residual
//                   (total - survived - blew_up - open_at_end), not folded
//                   silently into any of the three named buckets.
function classifyCandidate(result) {
  if (result.blowups.length > 0) return 'blew_up';
  if (result.openAtEnd) return 'open_at_end';
  const profit = result.balanceEnd - result.balanceStart;
  return profit > 0 ? 'survived' : 'resolved_at_loss';
}

