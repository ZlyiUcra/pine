// Pure compute for the ladder-cap replay: log parsing, the one-deal-at-a-time
// serial filter, the ladder simulation, and day aggregation. No process.exit,
// no console.log, no fs - callers own argv, I/O and printing.
//
// Shared by checks/ladder-cap.js (CLI) and the Electron app in
// ladder-cap-gui/ (see .specify/consilium/2026-08-07-electron-ladder-cap-gui.md
// for why this must be one module, not two copies).
//
// Data contract agreed in that verdict:
//   - win / carried (block used up, no win yet, paper loss) / blowup (whole
//     ladder used up, real deposit loss) are kept as three separate outcomes,
//     never merged into a single "against" count.
//   - a window is assigned to the day it CLOSED, not the day it opened.
//   - the counting unit for "how many trades" is windows (post one-at-a-time
//     filter), not raw log rows.

// ---------------------------------------------------------------------------
// Time - same UTC+1, minutes-since-epoch arithmetic as checks/closed-chains.js.
// ---------------------------------------------------------------------------
function toMin(stamp, dateFrom, yearHint) {
  if (!stamp) return null;
  const s = stamp.trim();
  if (!s) return null;

  let m = /^(\d{1,2}):(\d{2})$/.exec(s);
  if (m) {
    if (dateFrom == null) return null;
    const day = Math.floor(dateFrom / 1440) * 1440;
    return day + Number(m[1]) * 60 + Number(m[2]);
  }

  m = /^(\d{4})-(\d{2})-(\d{2})[ T](\d{1,2}):(\d{2})/.exec(s);
  if (m) return Math.floor(Date.UTC(+m[1], +m[2] - 1, +m[3], +m[4], +m[5]) / 60000);

  // MM-dd HH:mm - mar1GatesScanner.pine's per-entry log lines (MAR1GSCLOSE and
  // its own open/close/entryTimes fields), which carry no year at all
  // (str.format_time(..., 'MM-dd HH:mm', 'UTC+1')). Only reached with an
  // explicit yearHint: a paste from Pine Logs is not guaranteed to sit next to
  // a dated GCLOSE row to infer it from, so the year is a caller-supplied
  // parameter rather than a guess - see
  // .specify/consilium/2026-08-11-ladder-cap-payout-crossref.md.
  m = /^(\d{2})-(\d{2}) (\d{1,2}):(\d{2})$/.exec(s);
  if (m) {
    if (yearHint == null) return null;
    return Math.floor(Date.UTC(yearHint, +m[1] - 1, +m[2], +m[3], +m[4]) / 60000);
  }

  return null;
}

function hhmm(min) {
  if (min == null) return '  -  ';
  const d = new Date(min * 60000);
  const p = (n) => String(n).padStart(2, '0');
  return p(d.getUTCHours()) + ':' + p(d.getUTCMinutes());
}

function dayOf(min) {
  if (min == null) return '';
  return new Date(min * 60000).toISOString().slice(0, 10);
}

function stampRel(min, refDay) {
  if (min == null) return '  -  ';
  const d = dayOf(min);
  return d === refDay ? hhmm(min) : d.slice(5) + ' ' + hhmm(min);
}

// ---------------------------------------------------------------------------
// Parsing - naive on purpose (indexOf + split(';')), same as before. Only
// safe because the log is machine-generated by mar1GatesScanner.pine /
// mar1Scanner.pine and never carries a ';' inside a field.
// ---------------------------------------------------------------------------
function parseLog(text, yearHint) {
  const rows = [];
  for (const raw of text.split(/\r?\n/)) {
    const gi = raw.indexOf('GCLOSE;');
    const hi = raw.indexOf('GCLOSEHDR;');
    const mi = raw.indexOf('MAR1CLOSE;');
    const gsi = raw.indexOf('MAR1GSCLOSE;');
    if (hi >= 0) continue;

    if (gi >= 0) {
      const p = raw.slice(gi).split(';');
      if (p.length < 8) continue;
      const close = toMin(p[5]);
      rows.push({ pair: p[2].trim(), gate: p[3].trim() || '-', open: toMin(p[4], close), close, ent: Number(p[6]) || 0, side: (p[7] || '').trim(), entryTimes: null });
      continue;
    }

    if (mi >= 0) {
      const p = raw.slice(mi).split(';');
      if (p.length < 6) continue;
      const close = toMin(p[3]);
      rows.push({ pair: p[1].trim(), gate: '-', open: toMin(p[2], close), close, ent: Number(p[4]) || 0, side: (p[5] || '').trim(), entryTimes: null });
      continue;
    }

    // MAR1GSCLOSE;{ticker};{slot};{firstEntTime};{close};{ent};{side};{entryTimes}
    // - mar1GatesScanner.pine's per-entry log for one closed window. A strict
    // superset of GCLOSE for the closed-window case (same pair/gate/open/
    // close/entries/side), plus the real timestamp of every individual entry
    // - see .specify/consilium/2026-08-11-ladder-cap-payout-crossref.md for
    // why this is parsed here rather than as a second, separate function.
    // Requires yearHint (see toMin) since every timestamp in this line is
    // 'MM-dd HH:mm' with no year; quietly skipped without one, same as any
    // other malformed row in this parser.
    if (gsi >= 0) {
      if (yearHint == null) continue;
      // joinTimes puts a comma inside the entryTimes field the moment a
      // window costs 2+ entries, which makes this the first MAR1* line whose
      // Message field a CSV export ever has a reason to double-quote - a
      // plain-text Pine Logs paste never quotes anything, but a CSV export
      // (Date,Message; this file's own shape) wraps the whole field in `"`
      // when it contains the column's own delimiter, leaving exactly one
      // trailing `"` on the end of the line to strip.
      let seg = raw.slice(gsi);
      if (seg.endsWith('"')) seg = seg.slice(0, -1);
      const p = seg.split(';');
      if (p.length < 8) continue;
      const close = toMin(p[4], null, yearHint);
      const open = toMin(p[3], close, yearHint);
      const entryTimesStr = p[7].trim();
      const entryTimes = entryTimesStr
        ? entryTimesStr.split(',').map((t) => toMin(t.trim(), close, yearHint)).filter((t) => t != null)
        : [];
      rows.push({ pair: p[1].trim(), gate: p[2].trim() || '-', open, close, ent: Number(p[5]) || 0, side: (p[6] || '').trim(), entryTimes });
    }
  }
  for (const r of rows) if (r.open == null) r.open = r.close;
  return rows;
}

// ---------------------------------------------------------------------------
// Payout log - po-payout-filter's own per-minute file, cross-referenced
// against a window's real entry times (see the MAR1GSCLOSE branch of
// parseLog above). See
// .specify/consilium/2026-08-11-ladder-cap-payout-crossref.md for the full
// contract this was written against.
// ---------------------------------------------------------------------------

// One line: 'HH:MM:SS PAIR=NN PAIR=NN ...', payout as a whole percent
// (po-payout-filter/README.md, "The payout log"). Comment lines ('#...',
// the file's own one-line header) are skipped. dateHint is 'YYYY-MM-DD' - the
// file itself only ever names its date in its filename and in that header
// comment, never on the data lines, so the caller (GUI/CLI) supplies it
// explicitly rather than this function guessing at either source. Malformed
// lines and out-of-range payout values (not 0-100, or not a number at all -
// a scrape gone wrong writes garbage, not an absence) are dropped silently,
// the same quiet-skip convention parseLog already uses throughout.
//
// payout comes back as a FRACTION (divided by 100), to match the convention
// LadderOptions.payout already uses everywhere else in this module - the log
// itself writes a whole percent and this is the one place that conversion
// happens.
function parsePayoutLog(text, dateHint) {
  const rows = [];
  if (!dateHint) return rows;
  const dm = /^(\d{4})-(\d{2})-(\d{2})$/.exec(dateHint.trim());
  if (!dm) return rows;
  const dayMin = Math.floor(Date.UTC(+dm[1], +dm[2] - 1, +dm[3]) / 60000);

  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const tm = /^(\d{1,2}):(\d{2}):(\d{2})\s+(.*)$/.exec(line);
    if (!tm) continue;
    const min = dayMin + Number(tm[1]) * 60 + Number(tm[2]);
    for (const tok of tm[4].split(/\s+/)) {
      const pm = /^([A-Za-z0-9_]+)=(\d+(?:\.\d+)?)$/.exec(tok);
      if (!pm) continue;
      const pct = Number(pm[2]);
      if (!Number.isFinite(pct) || pct < 0 || pct > 100) continue;
      rows.push({ min, pair: pm[1], payout: pct / 100 });
    }
  }
  return rows;
}

// O(1) lookup built once per loaded payout file (see the performance
// condition in the verdict this was written against - never rebuilt per
// candidate inside a combo-sweep). Keyed by exact pair + minute, since the
// matching rule below is an exact key, not a nearest-neighbour search.
function buildPayoutIndex(payoutRows) {
  const index = new Map();
  for (const r of payoutRows) index.set(r.pair + '|' + r.min, r.payout);
  return index;
}

// Matches each real entry of a closed window (LogRow.entryTimes) against the
// payout that was live one minute earlier. po-payout-filter writes its line
// one second before ITS minute closes (po-payout-filter/README.md, "The
// payout log") - so the reading logged at minute M-1 is the freshest one
// available the instant the candle at minute M, which the entry rides on,
// opens. null wherever no payout row covers that pair/minute - never a
// guess, and never conflated with "payout was below threshold": a caller
// counting coverage must treat null as "unknown", not as a failing entry.
function payoutAtEntries(row, payoutIndex) {
  if (!row.entryTimes || !row.entryTimes.length) return [];
  return row.entryTimes.map((t) => {
    const v = payoutIndex.get(row.pair + '|' + (t - 1));
    return v == null ? null : v;
  });
}

// ---------------------------------------------------------------------------
// Counterfactual payout filtering - see
// .specify/consilium/2026-08-11-ladder-cap-payout-counterfactual.md for the
// full contract this was written against (two stages, Stage A and v2, both
// described there in detail).
// ---------------------------------------------------------------------------

// Stage A - drops a WHOLE window from `windows` (must already be
// post-oneAtATime; filtering before it would let a different window take the
// vacated "one deal at a time" slot and silently change which windows are
// even in play) based on the payout of its LAST (winning) entry alone. The
// window's own `ent`/rung numbering is untouched - a passing window feeds
// simulateLadder() completely unmodified. Answers "would the final signal
// have been taken", not "what if an intermediate entry too was skipped" -
// see v2 below for that.
//
// A window is dropped, not kept, when its payout can't be determined at all
// (no entryTimes, entryTimes.length !== ent, or the last entry's payout is
// unknown) - user decision, 2026-08-11: an element with no payout reading is
// excluded from the calculation entirely, never counted as passing or
// failing the threshold.
function filterWindowsByLastEntryPayout(windows, payoutIndex, minPayout) {
  return windows.filter((r) => {
    if (!r.entryTimes || r.entryTimes.length !== r.ent || !r.entryTimes.length) return false;
    const payouts = payoutAtEntries(r, payoutIndex);
    const last = payouts[payouts.length - 1];
    return last != null && last >= minPayout;
  });
}

// v2 - flattens every real entry of every window into one chronological
// stream, deriving each entry's real win/loss outcome from its POSITION
// within its own window: a window's entries are only ever logged on a win
// (see LogRow's own contract), so every entry but the last was a loss, and
// the last was the win. A window is skipped WHOLE (contributes zero entries)
// when `entryTimes` is missing or its length does not match `ent` - the
// same all-or-nothing guard Stage A uses, never a silent truncation that
// could shift which entry looks like "the last one".
//
// Payout is attached here, from the same payoutIndex Stage A uses, so the
// caller filters the returned stream by `e.payout != null && e.payout >=
// threshold` as an explicit, visible step - never by relying on `null >= x`
// happening to coerce to false, which hides "unknown" behind "failed".
function flattenEntries(windows, payoutIndex) {
  const out = [];
  for (const r of windows) {
    if (!r.entryTimes || r.entryTimes.length !== r.ent || !r.entryTimes.length) continue;
    const last = r.entryTimes.length - 1;
    for (let i = 0; i <= last; i++) {
      const min = r.entryTimes[i];
      const p = payoutIndex.get(r.pair + '|' + (min - 1));
      out.push({ pair: r.pair, gate: r.gate, min, outcome: i === last ? 'win' : 'loss', payout: p == null ? null : p });
    }
  }
  out.sort((a, b) => a.min - b.min);
  return out;
}

// Replays a filtered, chronologically-sorted SimEntry[] (see flattenEntries)
// against one ladder schedule - the same rung-consumption math simulateLadder
// runs (stakesFor/profitAt/blocksForCap), one ENTRY per iteration instead of
// one WINDOW. A block's rung budget is now consumed one real entry at a time
// rather than in one lump per window: a loss entry uses exactly one rung of
// the current block, and the block advances once its own budget is spent. A
// window whose winning entry got filtered out simply contributes its
// surviving losses to the stream and never resolves on its own - the
// sequence keeps carrying until a later entry, from this window or any
// other, lands a win within the remaining budget. That is not a special case
// the code below has to name; it falls out of consuming one entry at a time.
function simulateLadderByEntry(entries, { cap, schedule, deposit, mult, steps, payout, maxRungs }) {
  const series = seriesSum(mult, steps);
  const rungLimit = maxRungs ?? steps;
  const blockSchedule = schedule ?? blocksForCap(cap, rungLimit);

  let balance = deposit;
  let minBalance = deposit;
  let wins = 0;
  let carried = 0;
  let sequences = 0;
  const blowups = [];
  const detail = [];

  let stakes = null;
  let pos = 0;
  let seqStart = null;
  let seqEntries = [];
  let blockIndex = 0;
  let blockUsed = 0;

  for (const e of entries) {
    if (stakes === null) {
      stakes = stakesFor(balance, mult, steps, series);
      pos = 0;
      seqStart = e;
      seqEntries = [];
      blockIndex = 0;
      blockUsed = 0;
      sequences++;
    }

    seqEntries.push(e);
    pos += 1;
    blockUsed += 1;
    const blockSize = blockSchedule[blockIndex];
    const blockStart = pos - blockUsed + 1;

    if (e.outcome === 'win') {
      const absRung = pos;
      const profit = profitAt(stakes, absRung, payout);
      balance += profit;
      wins++;
      detail.push({
        entry: e, stakes, blockStart, blockSize, absRung, profit, loss: null,
        balanceAfter: balance, outcome: 'win', seqEntries: seqEntries.slice()
      });
      stakes = null;
    } else {
      carried++;
      let blown = pos >= rungLimit;
      if (!blown && blockUsed >= blockSize) {
        blockIndex += 1;
        blockUsed = 0;
        if (blockIndex >= blockSchedule.length) blown = true;
      }
      let loss = null;
      if (blown) {
        loss = stakes.slice(0, pos).reduce((s, x) => s + x, 0);
        balance -= loss;
        blowups.push({ from: seqStart, at: e, entries: seqEntries.slice(), loss, balanceAfter: balance });
      }
      detail.push({
        entry: e, stakes, blockStart, blockSize, absRung: null, profit: null, loss,
        balanceAfter: balance, outcome: blown ? 'blowup' : 'carry', seqEntries: seqEntries.slice()
      });
      if (blown) stakes = null;
    }

    minBalance = Math.min(minBalance, balance);
  }

  return {
    schedule: blockSchedule, maxRungs: rungLimit, deposit, mult, steps, payout,
    entries, detail, wins, carried, sequences, blowups,
    balanceStart: deposit, balanceEnd: balance, minBalance,
    openAtEnd: stakes !== null ? { pos, seqEntries } : null
  };
}

// ---------------------------------------------------------------------------
// Session filter - startMinOfDay/endMinOfDay may each be null (unbounded).
// Checked against a window's OPEN time.
// ---------------------------------------------------------------------------
const dayMinOfDay = (min) => min - Math.floor(min / 1440) * 1440;

function filterSession(rows, startMinOfDay, endMinOfDay) {
  if (startMinOfDay == null && endMinOfDay == null) return rows;
  return rows.filter((r) => {
    const m = dayMinOfDay(r.open);
    if (startMinOfDay != null && m < startMinOfDay) return false;
    if (endMinOfDay != null && m >= endMinOfDay) return false;
    return true;
  });
}

// ---------------------------------------------------------------------------
// One deal at a time - session filtering must already have happened (see
// filterSession) so a window outside the session can never set `free` and
// block one inside it.
// ---------------------------------------------------------------------------
function oneAtATime(rows) {
  const byOpen = rows.slice().sort((a, b) => a.open - b.open || a.close - b.close);
  const windows = [];
  let free = -Infinity;
  for (const r of byOpen) {
    if (r.open >= free) {
      windows.push(r);
      free = r.close;
    }
  }
  return windows;
}

// ---------------------------------------------------------------------------
// The ladder
// ---------------------------------------------------------------------------
function seriesSum(mult, steps) {
  let s = 0;
  for (let i = 0; i < steps; i++) s += Math.pow(mult, i);
  return s;
}

function stakesFor(balance, mult, steps, series) {
  const base = balance / series;
  const st = [];
  // MAX(FLOOR.MATH(...), 1) in the spreadsheet this was checked against - a
  // stake is never allowed to floor down to 0 even when balance is small.
  for (let i = 0; i < steps; i++) st.push(Math.max(1, Math.floor(base * Math.pow(mult, i))));
  return st;
}

// Profit if the win lands on step n (1-based): what step n returns, minus
// everything staked to get there.
function profitAt(stakes, n, payout) {
  let priorLoss = 0;
  for (let i = 0; i < n - 1; i++) priorLoss += stakes[i];
  return stakes[n - 1] * payout - priorLoss;
}

// Evenly-spaced placement of each entry between a window's real open and
// real close - the log has no finer timestamp than that.
function stepTime(open, close, k, ent) {
  if (ent <= 1) return open;
  return Math.round(open + (close - open) * (k - 1) / (ent - 1));
}

// The explicit block list a single fixed `cap` has always meant: same rung
// count every block until the ladder is used up, with a short remainder block
// at the end when it does not divide evenly (cap 3 over 8 rungs is 3-3-2).
//
// Exported so a single fixed cap can be labeled by its real block shape
// wherever one is entered (the CLI's `--caps` sweep, the GUI's per-cap
// suggestion rows) without a second, byte-identical copy of this loop living
// in the caller - ladder-cap-gui/src/renderer/src/main.ts carried exactly
// that copy until this function was exported (2026-08-09).
function blocksForCap(cap, rungs) {
  const blocks = [];
  let pos = 0;
  while (pos < rungs) {
    const size = Math.min(cap, rungs - pos);
    blocks.push(size);
    pos += size;
  }
  return blocks;
}

// Replays `windows` (already one-at-a-time, chronological) against one
// ladder carved into blocks per window. Returns structured data only - no
// formatting, no I/O.
//
// Two ways to say what the blocks are:
//   - `cap`: one fixed rung count per block, repeated until the whole ladder
//     is covered (the original behaviour). Expanded here into the explicit
//     block list it always meant - cap 3 on 8 steps is 3-3-2.
//   - `schedule`: the block list written out. It is played ONCE and no
//     further: a schedule whose blocks add up to less than `steps` ends the
//     sequence when it runs out of blocks, it does NOT wrap back to its own
//     start (user correction, 2026-08-08 - "if it is 4-2-1 there is no fourth
//     position, you just exit"). So 4-2-1 burns at most 7 of 8 rungs and the
//     8th stake is never placed, exactly like the sum says.
//
// That makes a short schedule a genuinely different candidate from a longer
// one with the same prefix, not a rewrite of it: 4-2-1 gives up after 7 rungs
// where 4-2-1-1 plays the 8th.
//
// `maxRungs` (default `steps`, i.e. the original behaviour) is how many rungs
// a sequence is allowed to burn before it gives up and takes the loss. It is
// deliberately NOT the same knob as `steps`: `steps` still sizes the stakes
// (the deposit is divided across the full series), while `maxRungs` below it
// means the last rung's stake is computed but never placed. Since each rung
// is `mult` times the one before, the top rung alone is worth more than every
// rung under it combined - stopping one short turns a near-total wipe into a
// partial one and leaves the rest of the deposit available for the next
// sequence (user request, 2026-08-08). The cost is the wins that would have
// landed on that last rung: more blowups, each far cheaper.
function simulateLadder(windows, { cap, schedule, deposit, mult, steps, payout, maxRungs }) {
  const series = seriesSum(mult, steps);
  const rungLimit = maxRungs ?? steps;
  const blockSchedule = schedule ?? blocksForCap(cap, rungLimit);

  let balance = deposit;
  let minBalance = deposit;
  let wins = 0;
  let carried = 0;
  let sequences = 0;
  const blowups = [];
  const detail = [];

  let stakes = null;
  let pos = 0;
  let seqStart = null;
  let seqWindows = [];
  let blockIndex = 0;

  for (const r of windows) {
    if (stakes === null) {
      stakes = stakesFor(balance, mult, steps, series);
      pos = 0;
      seqStart = r;
      seqWindows = [];
      blockIndex = 0;
      sequences++;
    }

    const blockSize = Math.min(blockSchedule[blockIndex], rungLimit - pos);
    blockIndex++;
    const blockStart = pos + 1;
    seqWindows.push(r);

    if (r.ent <= blockSize) {
      const absRung = pos + r.ent;
      const profit = profitAt(stakes, absRung, payout);
      balance += profit;
      wins++;
      detail.push({
        r, stakes, blockStart, blockSize, absRung, profit, loss: null,
        balanceAfter: balance, outcome: 'win', seqWindows: seqWindows.slice()
      });
      stakes = null;
    } else {
      pos += blockSize;
      carried++;
      // Two ways a sequence runs out: it reached the rung limit, or the
      // schedule has no block left to play. The second is what makes a
      // schedule that adds up to less than the ladder stop early instead of
      // wrapping around to its own first block.
      const blown = pos >= rungLimit || blockIndex >= blockSchedule.length;
      let loss = null;
      if (blown) {
        // Only the rungs actually played, not the whole stakes array - the
        // stakes above `pos` were computed but never placed, so they were
        // never lost. That covers both stopping cases: a short schedule and a
        // rungLimit below steps. When the schedule covers the whole ladder
        // this sums every stake, same as before.
        loss = stakes.slice(0, pos).reduce((s, x) => s + x, 0);
        balance -= loss;
        blowups.push({ from: seqStart, at: r, windows: seqWindows.slice(), loss, balanceAfter: balance });
      }
      detail.push({
        r, stakes, blockStart, blockSize, absRung: null, profit: null, loss,
        balanceAfter: balance, outcome: blown ? 'blowup' : 'carry', seqWindows: seqWindows.slice()
      });
      if (blown) stakes = null;
    }

    minBalance = Math.min(minBalance, balance);
  }

  return {
    cap, schedule: blockSchedule, deposit, mult, steps, payout, maxRungs: rungLimit,
    windows, detail, wins, carried, sequences, blowups,
    balanceStart: deposit, balanceEnd: balance, minBalance,
    openAtEnd: stakes !== null ? { pos, seqWindows } : null
  };
}

// ---------------------------------------------------------------------------
// Day aggregation - a window is assigned to the day it CLOSED (verdict
// decision, 2026-08-07). Days are visited in the order windows resolve, i.e.
// chronological, so balanceStart/balanceEnd per day are exact running values,
// not recomputed.
// ---------------------------------------------------------------------------
function dailyStats(result) {
  const days = [];
  const byDay = new Map();
  let runningBalance = result.balanceStart;

  for (const d of result.detail) {
    const day = dayOf(d.r.close);
    let entry = byDay.get(day);
    if (!entry) {
      entry = { day, windows: 0, wins: 0, carried: 0, blowups: 0, balanceStart: runningBalance, balanceEnd: runningBalance };
      byDay.set(day, entry);
      days.push(entry);
    }
    entry.windows++;
    if (d.outcome === 'win') entry.wins++;
    else if (d.outcome === 'blowup') entry.blowups++;
    else entry.carried++;
    entry.balanceEnd = d.balanceAfter;
    runningBalance = d.balanceAfter;
  }

  for (const entry of days) {
    entry.growthPct = entry.balanceStart ? (entry.balanceEnd / entry.balanceStart - 1) * 100 : 0;
  }
  return days;
}

// Compound return over the whole simulated period - deliberately separate
// from any per-day average so the two never collapse into one ambiguous
// "average % growth" figure (verdict decision, 2026-08-07).
function periodReturn(result) {
  return result.balanceStart ? (result.balanceEnd / result.balanceStart - 1) * 100 : 0;
}

// ---------------------------------------------------------------------------
// Cap combinations - every ordered way to mix cap values across the blocks
// of one ladder, instead of one fixed cap for the whole thing. Only
// combinations whose blocks sum to exactly `steps` are generated here: the
// shapes that use up the whole ladder if nothing wins first, and so the ones
// worth comparing against each other for "how many of these ever blow up".
//
// Each combination is replayed as a `schedule` through simulateLadder
// against the WHOLE loaded log, exactly like any other schedule - not
// sampled against isolated historical chains. An earlier version of the GUI
// scored candidates against pre-extracted chains and that disagreed with
// running the schedule for real: which windows even end up forming a chain
// together depends on the schedule that is running, so a combination that
// looked safe in isolation could still blow up once it is the thing
// actually deciding where sequences start and end (found 2026-08-08). There
// is no "caller's chain" this generates against - only steps and a value
// set.
// ---------------------------------------------------------------------------
function capCombinations(caps, steps) {
  const results = [];
  const path = [];
  (function rec(remaining) {
    if (remaining === 0) {
      results.push(path.slice());
      return;
    }
    for (const c of caps) {
      if (c > 0 && c <= remaining) {
        path.push(c);
        rec(remaining - c);
        path.pop();
      }
    }
  })(steps);
  return results;
}

// Same idea as capCombinations, but every non-empty prefix - sum anywhere
// from 1 up to `steps`, not only exactly `steps` - counts as a candidate.
// A schedule that adds up to less than steps is a genuinely different
// candidate, not a shorter way of writing a longer one: simulateLadder plays
// a schedule once and stops when its blocks run out, so [3, 2] gives up after
// 5 rungs where [3, 2, 3] plays all 8 (user correction, 2026-08-08 - this
// used to wrap around, and these prefixes used to be duplicates because of
// it).
function capCombinationsUpTo(caps, steps) {
  const results = [];
  const path = [];
  (function rec(remaining) {
    if (path.length > 0) results.push(path.slice());
    if (remaining === 0) return;
    for (const c of caps) {
      if (c > 0 && c <= remaining) {
        path.push(c);
        rec(remaining - c);
        path.pop();
      }
    }
  })(steps);
  return results;
}

// How far into a schedule a sequence actually had to go before it ended,
// counted over the whole period: index 0 is "won or blew up while still in
// the first block", index 1 is "needed the second block too", and so on. For
// 4-2-1 that reads as how many sequences finished inside the first four
// rungs, how many needed the 2 after it, and how many reached the trailing 1
// (user request, 2026-08-08).
//
// A sequence always opens with blockStart 1 (pos is 0 only at the start of
// one), which is what marks the boundary here. Carried windows are not
// counted - they did not end anything - and a sequence still open when the
// log runs out never lands in any bucket, so the buckets sum to the resolved
// sequences rather than to `sequences`. The list never runs past the
// schedule's own length - a schedule is played once and then the sequence is
// over, so 4-2-1 has exactly three buckets and no fourth.
//
// Moved here from the GUI (2026-08-09) once the CLI's combination-survival
// report became a second real consumer of the exact same computation over
// the exact same `result.detail` shape - see blocksForCap above for the
// same move made for the same reason a day earlier.
function resolvedByBlock(detail) {
  const counts = [];
  let block = 0;
  for (const d of detail) {
    block = d.blockStart === 1 ? 1 : block + 1;
    if (d.outcome === 'carry') continue;
    while (counts.length < block) counts.push(0);
    counts[block - 1] += 1;
  }
  return counts;
}

// Shared walk behind both averages below: total/count of (resolving
// window's close - sequence's first window's open), in minutes, over every
// detail entry `matches` accepts. A carried block is never itself a
// resolution and is never asked about here - only a 'win' or 'blowup' entry
// carries a complete `seqWindows` back to the sequence's first window.
function avgSequenceMinutesWhere(detail, matches) {
  let total = 0;
  let count = 0;
  for (const d of detail) {
    if (!matches(d)) continue;
    const first = d.seqWindows[0];
    if (!first || first.open == null || d.r.close == null) continue;
    total += d.r.close - first.open;
    count += 1;
  }
  return count ? total / count : null;
}

// Average wall-clock length of a RESOLVED sequence under one schedule, in
// minutes: from the open of the sequence's first window to the close of the
// window that resolved it, win OR blowup, averaged over every sequence that
// actually resolved either way. Distinct from "average length of one
// window" (a fixed property of the log, does not vary by schedule) and from
// avgSequenceMinutesToWin below (win only) - a schedule whose blowups drag
// on far longer than its wins, or the reverse, is exactly what comparing
// the two is for (2026-08-09, user request). null when nothing resolved.
function avgSequenceMinutes(detail) {
  return avgSequenceMinutesWhere(detail, (d) => d.outcome !== 'carry');
}

// Same average, WIN outcomes only - "how long does it typically take to get
// paid", as distinct from avgSequenceMinutes above, which also counts the
// (often much longer or much shorter, depending on the schedule) sequences
// that ended in a blowup instead (user request, 2026-08-09). null when this
// schedule never won outright on this run.
function avgSequenceMinutesToWin(detail) {
  return avgSequenceMinutesWhere(detail, (d) => d.outcome === 'win');
}

// The single shared text for both averages above, in both CLI output and
// the GUI's table cells, so the two surfaces cannot render the same number
// two different ways. Ten-thousandths of a minute plus a human breakdown in
// parentheses (user request, 2026-08-09): "10.7234 min (10m 43.40s)". The
// 60.00s guard is real, not defensive dressing - flooring the whole minutes
// and taking the remainder in seconds can round the remainder up to 60.00
// at the hundredths place (e.g. 9.999995 min floors to 9, remainder rounds
// to 60.00s) without it.
function formatSeqMinutes(minutes) {
  if (minutes == null) return '-';
  let wholeMin = Math.floor(minutes);
  let sec = Math.round((minutes - wholeMin) * 60 * 100) / 100;
  if (sec >= 60) {
    sec -= 60;
    wholeMin += 1;
  }
  return minutes.toFixed(4) + ' min (' + wholeMin + 'm ' + sec.toFixed(2) + 's)';
}

// Display order for a list of schedules, unrelated to any simulated
// outcome: fewer blocks first, and within one block count the blocks
// compared element-wise in DESCENDING order (6-3 before 5-4 before 4-5
// before 3-6) - the order requested for the combination-survival lists
// (user request, 2026-08-09), replacing a profit-based sort there entirely.
function compareSchedules(a, b) {
  if (a.length !== b.length) return a.length - b.length;
  for (let i = 0; i < a.length; i++) {
    if (a[i] !== b[i]) return b[i] - a[i];
  }
  return 0;
}

